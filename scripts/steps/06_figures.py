# Fig 5
print("  Fig 5: High vs Low exchange rates...")
try:
    high_avg, low_avg, sorted_mets = get_high_low_rates()
    met_labels = [COL2NAME.get(m, m) for m in sorted_mets]
    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    y = np.arange(len(sorted_mets)); w = 0.36
    vh = [high_avg.get(m, 0) for m in sorted_mets]
    vl = [low_avg.get(m, 0) for m in sorted_mets]
    axes[0].barh(y + w/2, vh, w, color=P["high"], label=f"High (n={len(high_clones)})", edgecolor="k", lw=0.4, zorder=3)
    axes[0].barh(y - w/2, vl, w, color=P["low"], label=f"Low (n={len(low_clones)})", edgecolor="k", lw=0.4, zorder=3)
    axes[0].set_yticks(y); axes[0].set_yticklabels(met_labels, fontsize=8.5)
    axes[0].axvline(0, color="k", lw=0.8)
    axes[0].set_xlabel("Exchange Rate (mmol/gDCW/h)\n(neg=uptake, pos=secretion)")
    axes[0].set_title("(A) High vs Low Producer")
    axes[0].legend(); ax_grid(axes[0])
    delta = [high_avg.get(m, 0) - low_avg.get(m, 0) for m in sorted_mets]
    axes[1].barh(y, delta, color=[P["high"] if d > 0 else P["low"] for d in delta], edgecolor="k", lw=0.4, zorder=3)
    axes[1].axvline(0, color="k", lw=0.8)
    axes[1].set_yticks(y); axes[1].set_yticklabels(met_labels, fontsize=8.5)
    axes[1].set_xlabel("Delta Rate = High - Low (mmol/gDCW/h)")
    axes[1].set_title("(B) Difference (High - Low)")
    axes[1].legend(handles=[mpatches.Patch(color=P["high"], label="Higher in High"), mpatches.Patch(color=P["low"], label="Lower in High")], loc="lower right")
    ax_grid(axes[1])
    fig.suptitle(f"Figure 5. Exchange Rate Comparison: High vs Low Producer\n(High={high_clones}, Low={low_clones})", fontsize=11, fontweight="bold")
    plt.tight_layout()
    save_figure(fig, "Fig5_high_vs_low_rates.png", DATASET)
except Exception as e:
    print(f"  !! Fig 5 오류: {e}")

