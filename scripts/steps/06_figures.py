    fig, ax = plt.subplots(figsize=(max(12, len(MET_COLS) * 0.7), 5))
    sns.heatmap(rate_matrix, ax=ax, cmap="RdBu_r", center=0, annot=True, fmt=".3f", linewidths=0.4, linecolor="white", cbar_kws={"label": "Rate (mmol/gDCW/h)\nneg=uptake, pos=secretion", "shrink": 0.7}, annot_kws={"size": 7.5})
    ax.set_title(f"Figure 2. Exchange Rate Heatmap\n(Day {data['day_interval'][0]}→{data['day_interval'][1]}, feed-corrected, sorted by IgG titer)")
    ax.set_xlabel("Metabolite")
    ax.set_ylabel("Clone (sorted by IgG)")
    ax.tick_params(axis="x", rotation=45)
    ax.tick_params(axis="y", rotation=0)
    plt.tight_layout()
    save_figure(fig, "Fig2_rate_heatmap.png", DATASET)
