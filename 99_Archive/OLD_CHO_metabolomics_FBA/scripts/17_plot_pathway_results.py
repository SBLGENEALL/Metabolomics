from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def make_heatmap(df: pd.DataFrame, value_col: str, title: str, out: Path):
    pivot = df.pivot_table(index="condition", columns="pathway", values=value_col, aggfunc="mean")
    pivot = pivot.sort_index()
    if pivot.empty:
        return

    data = pivot.to_numpy(dtype=float)
    fig, ax = plt.subplots(figsize=(max(9, 0.8 * len(pivot.columns)), max(5, 0.45 * len(pivot.index))))
    im = ax.imshow(data, aspect="auto")
    ax.set_xticks(range(len(pivot.columns)))
    ax.set_xticklabels(pivot.columns, rotation=45, ha="right")
    ax.set_yticks(range(len(pivot.index)))
    ax.set_yticklabels(pivot.index)
    ax.set_title(title)
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label(value_col)

    for i in range(data.shape[0]):
        for j in range(data.shape[1]):
            val = data[i, j]
            if np.isfinite(val):
                ax.text(j, i, f"{val:.2g}", ha="center", va="center", fontsize=7)

    fig.tight_layout()
    fig.savefig(out, dpi=300)
    print("[OK] saved:", out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    args = ap.parse_args()

    base = Path(args.base)
    table_dir = base / "results" / "tables" / "pathway"
    fig_dir = base / "results" / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)

    summary_path = table_dir / "pathway_interval_summary.csv"
    if not summary_path.exists():
        raise FileNotFoundError(summary_path)

    df = pd.read_csv(summary_path)
    if df.empty:
        print("[WARN] empty pathway summary")
        return

    for c in ["day_start", "day_end", "pfba_sum_abs_flux", "pfba_net_flux", "fva_sum_range"]:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")

    df = df[df["pathway"] != "MODEL"].copy()

    make_heatmap(
        df,
        "pfba_sum_abs_flux",
        "Pathway pFBA activity, mean across intervals",
        fig_dir / "pathway_pfba_heatmap.png",
    )

    if "fva_sum_range" in df.columns:
        make_heatmap(
            df,
            "fva_sum_range",
            "Pathway FVA flexibility, mean across intervals",
            fig_dir / "pathway_fva_flexibility_heatmap.png",
        )

    # Trend plot per pathway
    for pathway, subp in df.groupby("pathway"):
        fig, ax = plt.subplots(figsize=(11, 5.8))
        for cond, sub in subp.sort_values(["condition", "day_start"]).groupby("condition"):
            ax.plot(sub["day_end"], sub["pfba_sum_abs_flux"], marker="o", label=str(cond))
        ax.set_xlabel("Culture day, interval end")
        ax.set_ylabel("pFBA sum absolute flux")
        ax.set_title(f"Pathway activity trend: {pathway}")
        ax.grid(True, linestyle=":", alpha=0.5)
        ax.legend(fontsize=7, ncol=2)
        fig.tight_layout()
        out = fig_dir / f"pathway_{pathway}_by_interval.png"
        fig.savefig(out, dpi=300)
        print("[OK] saved:", out)

    # Export compact table for review
    clone_summary = df.groupby(["condition", "pathway"], as_index=False).agg(
        mean_pfba_sum_abs_flux=("pfba_sum_abs_flux", "mean"),
        mean_pfba_net_flux=("pfba_net_flux", "mean"),
        mean_fva_sum_range=("fva_sum_range", "mean") if "fva_sum_range" in df.columns else ("pfba_sum_abs_flux", "mean"),
    )
    out_table = table_dir / "pathway_clone_plot_summary.csv"
    clone_summary.to_csv(out_table, index=False, encoding="utf-8-sig")
    print("[OK] saved:", out_table)


if __name__ == "__main__":
    main()
